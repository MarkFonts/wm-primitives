// Generates the page-chunked glyph-name data for GlyphPicker's `names` prop.
//   node shared/scripts/gen-glyph-names.mjs
// Fetches UnicodeData.txt (official names) + AGLFN (Adobe "nice names"), then emits
// src/glyphNames/page-<n>.ts — one module per 2048-codepoint page that has data —
// plus pages.ts (the index of pages that exist). Consumers lazy-import only the
// pages a font's cmap touches, so a Latin font loads a few KB, never the world.
// CJK unified ideographs + Hangul syllables are EXCLUDED here: their names are
// algorithmic (prefix+hex / jamo composition) and computed at runtime for free.
import { writeFileSync, mkdirSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'glyphNames')
const PAGE = 0x800

const fetchText = async url => {
  const r = await fetch(url)
  if (!r.ok) throw new Error(`${url}: ${r.status}`)
  return r.text()
}

const [ucd, aglfn] = await Promise.all([
  fetchText('https://www.unicode.org/Public/UCD/latest/ucd/UnicodeData.txt'),
  fetchText('https://raw.githubusercontent.com/adobe-type-tools/agl-aglfn/master/aglfn.txt'),
])

// cp -> [nice?, unicodeName?]
const names = new Map()

for (const line of ucd.split('\n')) {
  const [cpHex, name] = line.split(';')
  if (!cpHex || !name || name.startsWith('<')) continue // ranges/controls: algorithmic or unnamed
  const cp = parseInt(cpHex, 16)
  names.set(cp, [undefined, name])
}
for (const line of aglfn.split('\n')) {
  if (line.startsWith('#')) continue
  const [cpHex, glyphName] = line.split(';')
  if (!cpHex || !glyphName) continue
  const cp = parseInt(cpHex, 16)
  const e = names.get(cp) ?? [undefined, undefined]
  e[0] = glyphName
  names.set(cp, e)
}

// bucket into pages
const pages = new Map()
for (const [cp, e] of names) {
  const p = cp >> 11
  if (!pages.has(p)) pages.set(p, [])
  pages.get(p).push([cp, e])
}

rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

const esc = s => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
let total = 0
for (const [p, entries] of [...pages.entries()].sort((a, b) => a[0] - b[0])) {
  entries.sort((a, b) => a[0] - b[0])
  const body = entries
    .map(([cp, [nice, uni]]) => `[0x${cp.toString(16)},${nice ? `'${esc(nice)}'` : '0'},${uni ? `'${esc(uni)}'` : '0'}]`)
    .join(',\n')
  const src = `// Generated by gen-glyph-names.mjs — do not edit.\n// [codepoint, niceName|0, unicodeName|0]\nexport default [\n${body},\n] as [number, string | 0, string | 0][]\n`
  writeFileSync(join(OUT, `page-${p}.ts`), src)
  total += entries.length
}
writeFileSync(join(OUT, 'pages.ts'),
  `// Generated by gen-glyph-names.mjs — do not edit.\nexport const NAME_PAGES = new Set<number>([${[...pages.keys()].sort((a, b) => a - b).join(', ')}])\n`)
console.log(`wrote ${pages.size} pages, ${total} named codepoints -> ${OUT}`)
